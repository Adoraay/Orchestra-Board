const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { NtExecutable, NtExecutableResource, Resource, Data } = require('resedit');
const { prepareRuntime } = require('../scripts/prepare-runtime.cjs');

test('launcher runtime embeds Orchestra metadata and all logo sizes without changing Electron; unchanged builds reuse it', { skip: process.platform !== 'win32' }, async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'orchestra-launcher-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const dist = path.join(root, 'node_modules', 'electron', 'dist');
  fs.mkdirSync(dist, { recursive: true });
  fs.mkdirSync(path.join(root, 'build'));
  const source = Buffer.from(NtExecutable.createEmpty(false, false).generate());
  fs.writeFileSync(path.join(dist, 'electron.exe'), source);
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ version: '0.1.3', build: { copyright: 'Orchestra' } }));
  const logo = fs.readFileSync(path.join(__dirname, '..', 'build', 'icon.ico'));
  fs.writeFileSync(path.join(root, 'build', 'icon.ico'), logo);
  const first = await prepareRuntime(root);
  assert.equal(first.reused, false);
  assert.equal(path.basename(first.executable), 'Orchestra.exe');
  assert.deepEqual(fs.readFileSync(path.join(dist, 'electron.exe')), source);
  const resources = NtExecutableResource.from(NtExecutable.from(fs.readFileSync(first.executable)));
  const info = Resource.VersionInfo.fromEntries(resources.entries)[0];
  const strings = info.getStringValues(info.getAllLanguagesForStringValues()[0]);
  assert.equal(strings.FileDescription, 'Orchestra');
  assert.equal(strings.ProductName, 'Orchestra');
  assert.equal(strings.OriginalFilename, 'Orchestra.exe');
  assert.equal(strings.ProductVersion, '0.1.3');
  const expected = Data.IconFile.from(logo).icons.map((item) => Buffer.from(item.data.bin));
  const actual = Resource.IconGroupEntry.fromEntries(resources.entries)[0].getIconItemsFromEntries(resources.entries).map((item) => Buffer.from(item.bin));
  assert.deepEqual(actual, expected, 'every Windows icon size matches the Orchestra logo');
  const timestamp = fs.statSync(first.executable).mtimeMs;
  const second = await prepareRuntime(root);
  assert.equal(second.reused, true);
  assert.equal(fs.statSync(second.executable).mtimeMs, timestamp);
  fs.writeFileSync(path.join(root, 'package.json'), JSON.stringify({ version: '0.1.4' }));
  assert.equal((await prepareRuntime(root)).reused, false, 'a version change regenerates metadata');
  assert.deepEqual(fs.readFileSync(path.join(dist, 'electron.exe')), source);
});
