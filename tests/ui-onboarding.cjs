const assert = require('assert/strict');
const fs = require('fs');
const path = require('path');

module.exports = async ({ win, evaluate, until, sleep, data, errors }) => {
  const french = process.env.ORCHESTRA_SMOKE_MODE.endsWith('-fr');
  const tr = (en, fr) => french ? fr : en;
  const click = async (selector) => { await until(`!!document.querySelector(${JSON.stringify(selector)})`); await evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`); };
  const button = async (text, scope = 'document') => {
    const expression = `[...${scope}.querySelectorAll('button')].find(b => b.textContent.trim() === ${JSON.stringify(text)})`;
    await until(`!!(${expression})`); await evaluate(`(${expression}).click()`);
  };
  const next = () => button(tr('Next', 'Suivant'), "document.querySelector('.setup-footer')");
  const capture = async (name) => {
    await win.webContents.capturePage(undefined, { stayHidden: true }); await sleep(200);
    fs.writeFileSync(path.join(data, name + (french ? '-fr' : '') + '.png'), (await win.webContents.capturePage(undefined, { stayHidden: true })).toPNG());
  };
  await until("!!document.querySelector('.setup-dialog .setup-folder') && !document.querySelector('.splash') && Number(getComputedStyle(document.querySelector('.splash-backdrop')).opacity) === 0");
  assert.equal(await evaluate("!!document.querySelector('.setup-dialog select')"), true, 'original language step is present');
  await capture('phase4-onboarding');
  await button(tr('Choose folder', 'Choisir un dossier'));
  await until("document.querySelector('.setup-folder').textContent.includes('chosen-project')");
  await next();
  await until("document.querySelectorAll('.setup-dialog .theme-card').length === 8");
  await capture('phase4-original-themes');
  await evaluate("document.querySelector('.setup-dialog [data-theme=\"light\"]').closest('button').click()");
  await until("document.documentElement.dataset.theme === 'light'");
  await next();
  await until("!!document.querySelector('#terminal-font-size')");
  await next();
  await until("!!document.querySelector('.setup-dialog .segmented')");
  await next();
  await until("!!document.querySelector('.glow-settings')");
  await next();
  await until("document.querySelectorAll('.setup-agents .install-badge').length >= 3");
  const badges = await evaluate("[...document.querySelectorAll('.setup-agents .install-badge')].map(el => el.textContent)");
  assert.ok(badges.every((text) => text === tr('not installed', 'non installé')));
  await capture('phase4-original-agents');
  await next();
  await button(tr('Finish', 'Terminer'), "document.querySelector('.setup-footer')");
  await until("!!document.querySelector('.tutorial-bubble') && !document.querySelector('.setup-dialog')");
  await capture('phase4-original-tour');
  await button(tr('Quit the tour', 'Quitter la visite'));
  await until("!document.querySelector('.tutorial-bubble')");
  assert.deepEqual(require('../electron/ptyManager.cjs').ids(), [], 'configuration never starts agents');
  assert.equal((await evaluate('window.workspace.get()')).boards.length, 1);
  await click(`.topbar button[title^=${JSON.stringify(tr('Settings', 'Paramètres'))}]`);
  await button(tr('General', 'Général'));
  await button(tr('Replay the tour', 'Refaire la visite'));
  await until("!!document.querySelector('.tutorial-bubble') && !document.querySelector('.setup-dialog')");
  await button(tr('Quit the tour', 'Quitter la visite'));
  await click(`.topbar button[title^=${JSON.stringify(tr('Settings', 'Paramètres'))}]`);
  await button(tr('General', 'Général'));
  await button(tr('Replay initial setup', 'Refaire la configuration initiale'));
  await until("!!document.querySelector('.setup-dialog .setup-folder')");
  await button(tr('Skip', 'Passer'), "document.querySelector('.setup-footer')");
  await until("!!document.querySelector('.tutorial-bubble') && !document.querySelector('.setup-dialog')");
  await button(tr('Quit the tour', 'Quitter la visite'));
  await sleep(600);
  const settings = JSON.parse(fs.readFileSync(path.join(data, 'settings.json'), 'utf8'));
  assert.equal(settings.general.rootPath, path.join(data, 'chosen-project'));
  assert.equal(settings.appearance.theme, 'light');
  assert.equal(settings.general.tutorialDone, true);
  win.webContents.reload();
  await until("!!document.querySelector('.topbar') && !document.querySelector('.setup-dialog')");
  await sleep(700);
  assert.equal(await evaluate("!!document.querySelector('.setup-dialog')"), false, 'existing installation does not repeat onboarding');
  assert.deepEqual(errors, []);
};
