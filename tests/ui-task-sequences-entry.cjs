const fs = require('fs');
const os = require('os');
const path = require('path');
const assert = require('node:assert/strict');
const Module = require('module');
const { app, BrowserWindow } = require('electron');

const data = process.env.ORCHESTRA_SEQUENCES_UI_DATA;
const mode = process.env.ORCHESTRA_SEQUENCES_UI_MODE;
const artifacts = process.env.ORCHESTRA_SEQUENCES_UI_ARTIFACTS;
if (!data || path.dirname(path.resolve(data)) !== path.resolve(os.tmpdir()) || !path.basename(data).startsWith('orchestra-sequences-ui-')) throw new Error('Isolated profile required');
app.setPath('userData', data);
app.setPath('appData', path.join(data, 'appdata'));
process.env.CODEX_HOME = path.join(data, 'codex');
process.env.CLAUDE_CONFIG_DIR = path.join(data, 'claude');
app.setAppUserModelId = () => {};
BrowserWindow.prototype.show = () => {};
app.commandLine.appendSwitch('force-prefers-reduced-motion');
const nativeLoad = Module._load;
Module._load = function (request, ...args) {
  const value = nativeLoad.call(this, request, ...args);
  if (request !== 'electron') return value;
  return { ...value, BrowserWindow: function (options) { return new BrowserWindow({ ...options, show: false, webPreferences: { ...options.webPreferences, offscreen: true, backgroundThrottling: false } }); } };
};

// Les terminaux et modèles sont simulés ; le vrai preload, l'IPC et les hooks HTTP sont exercés.
const terminals = new Map();
const writes = [];
const pty = require('../electron/ptyManager.cjs');
pty.create = (options, onData, onExit) => { terminals.set(options.id, { options, onExit }); return { cwd: options.cwd, buffer: '' }; };
pty.write = (id, text) => writes.push({ id, text });
pty.resize = () => {};
pty.kill = (id) => terminals.delete(id);
pty.killAll = () => terminals.clear();
require('../electron/codexProfile.cjs').ensure = () => {};
const settings = require('../electron/settingsStore.cjs');
const loadSettings = settings.load;
settings.load = () => { const value = loadSettings(); return { ...value, agents: value.agents.map((agent) => ({ ...agent, resumeArgs: '' })) }; };
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const timeout = setTimeout(() => { console.error('UI test timed out'); app.exit(1); }, 55000);

app.on('browser-window-created', (_event, win) => {
  let started = false;
  const errors = [];
  win.webContents.on('console-message', (details) => { if (details.level === 'error') errors.push(details.message); });
  win.webContents.on('did-finish-load', async () => {
    if (started) return;
    started = true;
    const evaluate = (code) => win.webContents.executeJavaScript(code);
    const until = async (condition, label = 'condition') => {
      for (let i = 0; i < 160; i++) { if (await condition()) return; await sleep(50); }
      throw new Error(`Timed out: ${label}; page: ${await evaluate('document.body.innerText.slice(-1800)')}; errors: ${errors.join('; ')}`);
    };
    const domUntil = (expression) => until(() => evaluate(expression), expression);
    const button = (text) => evaluate(`[...document.querySelectorAll('.sequences-modal button')].find(button => button.textContent.trim() === ${JSON.stringify(text)})?.click()`);
    const set = (selector, value) => evaluate(`(() => { const element = document.querySelector(${JSON.stringify(selector)}); const prototype = element.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : element.tagName === 'SELECT' ? HTMLSelectElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(prototype, 'value').set.call(element, ${JSON.stringify(value)}); element.dispatchEvent(new Event(element.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true })); })()`);
    const hook = async (id, name, extra = {}) => {
      const response = await fetch(require('../electron/hookServer.cjs').hookUrl(id), { method: 'POST', body: JSON.stringify({ hook_event_name: name, session_id: `session-${id}`, ...extra }) });
      assert.equal(response.status, 200);
    };
    const pastes = () => writes.filter((value) => value.text.startsWith('\x1b[200~'));
    const lastRun = () => JSON.parse(fs.readFileSync(path.join(data, 'task-sequences.json'), 'utf8')).tasks[0].run;
    const fr = mode.startsWith('fr');
    try {
      await domUntil("!!document.querySelector('.topbar')");
      await domUntil("[...document.querySelectorAll('button')].some(button => ['New conversation', 'Nouvelle discussion'].includes(button.textContent.trim()))");
      await evaluate("[...document.querySelectorAll('button')].find(button => ['New conversation', 'Nouvelle discussion'].includes(button.textContent.trim())).click()");
      await until(() => terminals.size === 2, 'two mock terminals');
      await hook('a', 'SessionStart'); await hook('b', 'SessionStart');
      const toolbarWidth = () => evaluate("document.querySelector('.sequence-open').getBoundingClientRect().width");
      const hoverTasks = async () => {
        const point = await evaluate("(() => { const r = document.querySelector('.sequence-open').getBoundingClientRect(); return { x: Math.round(r.left + r.width / 2), y: Math.round(r.top + r.height / 2) }; })()");
        win.webContents.sendInputEvent({ type: 'mouseMove', ...point });
      };
      win.webContents.sendInputEvent({ type: 'mouseMove', x: 10, y: 60 });
      const compactWidth = await toolbarWidth();
      assert.ok(compactWidth <= 34);
      await hoverTasks();
      await until(async () => (await toolbarWidth()) > compactWidth + 20, 'toolbar expands on hover');
      win.webContents.sendInputEvent({ type: 'mouseMove', x: 10, y: 60 });
      await until(async () => (await toolbarWidth()) <= 34, 'toolbar collapses after hover');
      await evaluate("document.querySelector('.settings-toggle').click()");
      await domUntil("!!document.querySelector('#toolbar-hover')");
      assert.equal(await evaluate("document.querySelector('#toolbar-hover').checked"), true);
      assert.equal(await evaluate("[...document.querySelectorAll('[role=tab]')].some(tab => ['Diagnostics', 'Diagnostic'].includes(tab.textContent.trim()))"), true);
      await evaluate("document.querySelector('#toolbar-hover').click()");
      await until(() => JSON.parse(fs.readFileSync(path.join(data, 'settings.json'), 'utf8')).appearance.expandToolbarOnHover === false, 'hover preference saved disabled');
      await evaluate("document.querySelector('#settings-title').closest('.modal').querySelector('.modal-header button').click()");
      await hoverTasks(); await sleep(220);
      assert.ok((await toolbarWidth()) <= 34, 'disabled hover keeps the icon compact');
      assert.equal(await evaluate("window.settings.get().then(value => value.appearance.expandToolbarOnHover)"), false);
      await evaluate("document.querySelector('.settings-toggle').click()");
      await domUntil("!!document.querySelector('#toolbar-hover') && !document.querySelector('#toolbar-hover').checked");
      await evaluate("document.querySelector('#toolbar-hover').click()");
      await until(() => JSON.parse(fs.readFileSync(path.join(data, 'settings.json'), 'utf8')).appearance.expandToolbarOnHover === true, 'hover preference saved enabled');
      await evaluate("document.querySelector('#settings-title').closest('.modal').querySelector('.modal-header button').click()");
      await evaluate("document.querySelector('.sequence-open').click()");
      await domUntil("!!document.querySelector('.sequences-modal') && !document.querySelector('.sequence-editor input').disabled");
      const bounds = await evaluate("(() => { const r = document.querySelector('.sequences-modal').getBoundingClientRect(); return { width: r.width, height: r.height }; })()");
      assert.ok(bounds.width >= 950 && bounds.height >= 700, JSON.stringify(bounds));
      await set('.sequence-editor > .field input', fr ? 'Développer et relire' : 'Develop and review');
      await set('.sequence-step select', 'a');
      await set('.sequence-step textarea', fr ? 'Développe la page de connexion.' : 'Develop the login page.');
      await button(fr ? 'Ajouter une étape' : 'Add a step');
      await set('.sequence-step:nth-child(2) select', 'b');
      await set('.sequence-step:nth-child(2) textarea', fr ? 'Relis les changements et liste les problèmes.' : 'Review the changes and list the issues.');
      await evaluate("document.querySelectorAll('.sequence-step:nth-child(2) input[type=checkbox]').forEach(input => input.click())");
      await button(fr ? 'Enregistrer' : 'Save');
      await domUntil("document.querySelectorAll('.sequence-list-item').length === 1");
      await button(fr ? 'Lancer' : 'Run');
      await until(() => pastes().length === 1, 'first prompt sent');
      await sleep(300); await hook('a', 'UserPromptSubmit', { turn_id: 'dev' });
      await hook('a', 'Notification'); await sleep(150); assert.equal(pastes().length, 1);
      await button(fr ? 'Mettre en pause' : 'Pause');
      await hook('a', 'Stop', { turn_id: 'dev', last_assistant_message: 'Implemented login.js and its tests.' });
      await until(() => lastRun().index === 1, 'first response recorded while paused');
      assert.equal(lastRun().state, 'paused'); assert.equal(pastes().length, 1);
      await button(fr ? 'Reprendre' : 'Resume');
      await until(() => lastRun().state === 'approval', 'approval gate');
      await button(fr ? 'Valider et envoyer cette étape' : 'Approve and send this step');
      await until(() => pastes().length === 2, 'review prompt sent');
      assert.equal(pastes()[1].id, 'b'); assert.match(pastes()[1].text, /Implemented login.js and its tests/);
      await sleep(300); await hook('b', 'UserPromptSubmit', { turn_id: 'review' });
      await hook('b', 'Stop', { turn_id: 'review', last_assistant_message: 'Review complete: no blocking issues.' });
      await until(() => lastRun().state === 'completed', 'task completed');
      await domUntil("document.querySelector('.sequence-run.completed') !== null");
      await sleep(200);
      await win.webContents.capturePage(undefined, { stayHidden: true });
      const image = await win.webContents.capturePage(undefined, { stayHidden: true });
      fs.writeFileSync(path.join(artifacts, `${mode}-completed.png`), image.toPNG());
      assert.equal(await evaluate("document.querySelector('.sequence-main').scrollWidth <= document.querySelector('.sequence-main').clientWidth"), true);
      assert.equal(await evaluate("!!document.querySelector('.sequences-modal').innerText.match(/sequences\.[a-z]/)"), false);
      await button(fr ? 'Dupliquer' : 'Duplicate');
      await domUntil("document.querySelector('.sequence-editor > .field input').value.startsWith('Copie') || document.querySelector('.sequence-editor > .field input').value.startsWith('Copy')");
      await evaluate("document.querySelector('.sequences-modal .modal-header .icon-button').click()");
      await domUntil("!!document.querySelector('.sequence-confirm')");
      await button(fr ? 'Annuler' : 'Cancel');
      assert.equal(await evaluate("!!document.querySelector('.sequences-modal')"), true);
      await button(fr ? 'Enregistrer' : 'Save');
      await domUntil("document.querySelectorAll('.sequence-list-item').length === 2");
      await evaluate("document.querySelector('.sequences-modal .modal-header .icon-button').click()");
      await domUntil("!document.querySelector('.sequences-modal')");
      await evaluate("document.querySelector('.sequence-open').click()");
      await domUntil("document.querySelectorAll('.sequence-list-item').length === 2");
      await evaluate("document.querySelector('.sequences-modal .modal-header .icon-button').click()");
      await domUntil("!document.querySelector('.sequences-modal')");

      // Les trois outils historiques restent présents et utilisent leurs vraies API IPC.
      assert.equal(await evaluate("document.querySelectorAll('.search-toggle, .teams-toggle, .inbox-toggle').length"), 3);
      await evaluate("document.querySelector('.search-toggle').click()");
      await domUntil("!!document.querySelector('.search-field input')");
      await set('.search-field input', 'Claude Reviewer');
      await domUntil("document.querySelectorAll('.search-result').length === 1");
      await evaluate("document.querySelector('.search-result').click()");
      await domUntil("!document.querySelector('.search-palette') && !!document.querySelector('.react-flow__node[data-id=\"b\"].selected')");

      await evaluate("document.querySelector('.teams-toggle').click()");
      await domUntil("document.querySelectorAll('.team-item').length === 3");
      await evaluate("[...document.querySelectorAll('.team-modal [role=tab]')].find(button => button.textContent === " + JSON.stringify(fr ? 'Enregistrer ce tableau' : 'Save this board') + ").click()");
      await set('.team-modal input[type=text]', 'Restored team');
      await evaluate("[...document.querySelectorAll('.team-modal button')].find(button => button.textContent.trim() === " + JSON.stringify(fr ? 'Enregistrer comme modèle' : 'Save as a template') + ").click()");
      await domUntil("document.querySelectorAll('.team-item').length === 4");
      const savedTeam = JSON.parse(fs.readFileSync(path.join(data, 'team-templates.json'), 'utf8'))[0];
      assert.equal(savedTeam.name, 'Restored team');
      assert.equal(savedTeam.board.nodes.length, 2);
      assert.equal(savedTeam.board.nodes[0].data.cwd, undefined);
      await domUntil("!!document.querySelector('.team-modal .dialog-actions button.primary:not(:disabled)')");
      await evaluate("document.querySelector('.team-modal .dialog-actions button.primary').click()");
      await domUntil("!document.querySelector('.team-modal')");
      await until(() => terminals.size === 4, 'fresh agents from saved team');
      const restoredWorkspace = JSON.parse(fs.readFileSync(path.join(data, 'workspace.json'), 'utf8'));
      assert.equal(restoredWorkspace.boards.length, 2);
      assert.equal(restoredWorkspace.boards[1].name, 'Restored team');
      assert.ok(restoredWorkspace.boards[1].nodes.every(node => !['a', 'b'].includes(node.id)));

      await evaluate("window.dispatchEvent(new KeyboardEvent('keydown', { key: 'F', code: 'KeyF', ctrlKey: true, shiftKey: true, bubbles: true }))");
      await domUntil("!!document.querySelector('.search-palette')");
      await set('.search-field input', 'Claude Dev');
      await domUntil("document.querySelectorAll('.search-result').length === 2");
      assert.equal(await evaluate("new Set([...document.querySelectorAll('.search-board')].map(node => node.textContent)).size"), 2);
      await evaluate("document.querySelector('.search-field input').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))");
      await domUntil("!document.querySelector('.search-palette')");

      await hook('a', 'UserPromptSubmit', { turn_id: 'inbox' }); await hook('a', 'Notification');
      await domUntil("document.querySelector('.inbox-count')?.textContent === '1'");
      await evaluate("document.querySelector('.inbox-toggle').click()");
      await domUntil("document.querySelectorAll('.inbox-entry').length === 1");
      assert.match(await evaluate("document.querySelector('.inbox-entry').textContent"), /Claude Dev/);
      await evaluate("document.querySelector('.inbox-case').click()");
      await domUntil("!document.querySelector('.inbox-modal') && !!document.querySelector('.react-flow__node[data-id=\"a\"].selected')");
      await hook('a', 'Stop', { turn_id: 'inbox', last_assistant_message: 'Permission resolved.' });
      await domUntil("!document.querySelector('.inbox-count')");
      await evaluate("document.querySelector('.inbox-toggle').click()");
      await domUntil("!!document.querySelector('.inbox-modal')");
      assert.equal(await evaluate("document.querySelectorAll('.inbox-entry').length"), 0);
      await evaluate("document.querySelector('.inbox-tab-resolved').click()");
      await domUntil("document.querySelectorAll('.inbox-entry.resolved').length === 1");
      await evaluate("document.querySelector('.inbox-clear').click()");
      await domUntil("document.querySelectorAll('.inbox-entry').length === 0");
      await evaluate("document.querySelector('.inbox-modal .modal-header button').click()");
      assert.equal(await evaluate("!!document.body.innerText.match(/(?:team|inbox|search)\.[a-z]/)"), false);
      assert.deepEqual(errors, []);
      console.log(`PASS UI ${mode}: tasks, restored search and shortcut across boards, save/instantiate team, inbox permission/count/navigation/resolution; no renderer errors`);
      clearTimeout(timeout); app.quit();
    } catch (err) { console.error(err.stack); clearTimeout(timeout); app.exit(1); }
  });
});
