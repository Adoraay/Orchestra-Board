  const dict = { en, fr };
  // L'anglais de la page devient la référence des clés [data-i18n].
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    if (!(el.dataset.i18n in en)) en[el.dataset.i18n] = el.innerHTML;
  });

  let lang = 'en';
  function t(key, vars) {
    let text = dict[lang][key] ?? en[key] ?? key;
    if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, value);
    return text;
  }
  function setLang(next, remember) {
    lang = next === 'fr' ? 'fr' : 'en';
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      if (el.dataset.i18nLock !== undefined) return;
      el.innerHTML = t(el.dataset.i18n);
    });
    if (remember) try { localStorage.setItem('orchestra-lang', lang); } catch {}
    document.dispatchEvent(new CustomEvent('langchange'));
  }
  window.i18n = { t, setLang, get lang() { return lang; } };
